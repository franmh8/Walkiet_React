await page.getByText('+ Agregar Contacto',{exact:true}).click();
await page.getByPlaceholder('Ej. Juan Carlos',{exact:true}).fill('Contacto');
await page.getByPlaceholder('Ej. Perez Hernandez',{exact:true}).fill('Prueba');
await page.getByPlaceholder('771 123 4567',{exact:true}).fill('7715551234');
await page.getByPlaceholder('ejemplo@c5i.gob.mx',{exact:true}).fill('test@example.com');
await page.getByLabel('Guardar contacto',{exact:true}).click();
await page.getByText('No se pudo completar la operación de contactos (HTTP 200).',{exact:true}).waitFor();
assert.equal(await page.getByPlaceholder('Ej. Juan Carlos',{exact:true}).inputValue(),'Contacto');
assert.equal(contacts.length,0);
console.log('OK: error PHP HTTP 200 conserva formulario y no crea éxito local');
failCreate=false;
await page.getByLabel('Guardar contacto',{exact:true}).click();
assert.equal(await page.getByLabel('Guardar contacto',{exact:true}).getAttribute('aria-disabled'),'true');
await page.getByText('1 contactos cargados',{exact:true}).waitFor();
assert.equal(writes,2);
await page.reload();
await page.getByText('Contactos',{exact:true}).click();
await page.getByText('Contacto Prueba',{exact:true}).click();
await page.getByText('Editar',{exact:true}).click();
await page.getByPlaceholder('Ej. Juan Carlos',{exact:true}).fill('Editado');
await page.getByPlaceholder('771 123 4567',{exact:true}).fill('7715559876');
await page.getByPlaceholder('ejemplo@c5i.gob.mx',{exact:true}).focus();
await page.getByPlaceholder('ejemplo@c5i.gob.mx',{exact:true}).press('ControlOrMeta+A');
await page.getByPlaceholder('ejemplo@c5i.gob.mx',{exact:true}).press('Backspace');
await page.getByPlaceholder('ejemplo@c5i.gob.mx',{exact:true}).press('Tab');
await page.getByLabel('Guardar contacto',{exact:true}).click();
await page.getByText('Editado Prueba',{exact:true}).first().waitFor();
assert.equal(contacts[0].phone_number,'7715559876');assert.equal(contacts[0].email,'');
console.log('OK: crear y editar persiste tras recarga y usa respuesta del servidor');
await page.getByText('Eliminar Contacto',{exact:true}).click();
await page.getByLabel('Confirmar acción',{exact:true}).click();
await page.getByText('Error temporal de BD',{exact:true}).waitFor();
assert.equal(contacts.length,1);
await page.getByText('Entendido',{exact:true}).click();
console.log('OK: fallo de eliminación conserva contacto');
failDelete=false;
await page.getByText('Eliminar Contacto',{exact:true}).click();
await page.getByLabel('Confirmar acción',{exact:true}).click();
await page.getByText('0 contactos cargados',{exact:true}).waitFor();
await page.reload();
await page.getByText('Contactos',{exact:true}).click();
await page.getByText('0 contactos cargados',{exact:true}).waitFor();
assert.equal(contacts.length,0);assert.equal(writes,5);
await page.getByText('Chat',{exact:true}).click();
