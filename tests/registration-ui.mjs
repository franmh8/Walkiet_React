import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import mysql from 'mysql2/promise';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.REGISTRATION_TEST_BACKEND;
if(base!=='http://127.0.0.1:8119'||!process.env.CONTACTS_TEST_SOCKET?.startsWith('/tmp/'))throw Error('Usa solo la fixture local contacts_test_registration.');
const db=await mysql.createConnection({socketPath:process.env.CONTACTS_TEST_SOCKET,user:'root',database:'contacts_test_registration'});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']});
const provider='http://127.0.0.1:8110';
const control=failure=>fetch(provider+'/test/control',{method:'POST',body:JSON.stringify({failure})});
try {
  await db.execute('DELETE FROM security_rate_limits');
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('**/walkiet.alwaysdata.net/**',r=>r.abort());
  await context.addInitScript(server=>localStorage.setItem('c5i_native_server_url',server),base);
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.REGISTRATION_UI_URL||'http://localhost:3001');
  await page.getByText('Registrarse',{exact:true}).click();
  await page.getByPlaceholder('Roberto Morales',{exact:true}).fill('Registro Navegador');
  await page.getByPlaceholder('7712345678',{exact:true}).fill('7710000820');
  await page.getByPlaceholder('usuario@dominio.com',{exact:true}).fill('registration-ui@example.test');
  await page.getByPlaceholder('Contraseña',{exact:true}).fill('Synthetic-ui-28!');
  await page.getByPlaceholder('Repite',{exact:true}).fill('Synthetic-ui-28!');
  await control('send');await page.getByText('Continuar',{exact:true}).click();
  await page.getByText('No se pudo enviar el correo. Intenta de nuevo más tarde.',{exact:true}).waitFor();
  assert.equal(await page.getByText('Verificar correo',{exact:true}).count(),0);
  assert.equal(await page.getByPlaceholder('usuario@dominio.com',{exact:true}).inputValue(),'registration-ui@example.test');
  await control('');await db.execute('DELETE FROM security_rate_limits');
  await page.getByText('Continuar',{exact:true}).click();await page.getByText('Verificar correo',{exact:true}).waitFor();
  const message=(await(await fetch(provider+'/test/events')).json()).filter(m=>m.to==='registration-ui@example.test').at(-1);
  assert.ok(message?.code);assert.equal(await page.getByText('Verificar Celular',{exact:true}).count(),0);
  await page.getByText('Ingresa el código enviado a registration-ui@example.test',{exact:true}).waitFor();
  assert.equal(await page.getByText('Reenviar SMS',{exact:true}).count(),0);assert.equal(await page.getByText(message.code,{exact:true}).count(),0);
  assert.equal(await page.getByRole('textbox',{name:/Dígito \d del código/}).count(),6);
  await page.screenshot({path:'/tmp/registration-email-desktop.png',fullPage:true});
  await page.setViewportSize({width:320,height:740});
  const sixth=await page.getByLabel('Dígito 6 del código',{exact:true}).boundingBox();assert.ok(sixth.x+sixth.width<=320);
  await page.screenshot({path:'/tmp/registration-email-small.png',fullPage:true});
  await page.setViewportSize({width:430,height:932});
  await page.getByLabel('Dígito 1 del código',{exact:true}).fill('000000');await page.getByText('Validar',{exact:true}).click();
  await page.getByText('Código incorrecto. Revisa el correo e intenta nuevamente.',{exact:true}).waitFor();
  const [[before]]=await db.execute('SELECT COUNT(*) n FROM users WHERE correo=?',['registration-ui@example.test']);assert.equal(Number(before.n),0);
  await page.getByLabel('Dígito 1 del código',{exact:true}).fill(message.code);
  for(let i=0;i<6;i++)assert.equal(await page.getByLabel(`Dígito ${i+1} del código`,{exact:true}).inputValue(),message.code[i]);
  await page.screenshot({path:'/tmp/registration-email-mobile.png',fullPage:true});
  await page.getByText('Validar',{exact:true}).click();
  await page.getByText('¡Registro completado! Tu correo quedó verificado. Ya puedes iniciar sesión.',{exact:true}).waitFor();
  assert.equal(await page.getByPlaceholder('Ingresa tu teléfono o correo',{exact:true}).inputValue(),'7710000820');
  assert.equal(await page.getByPlaceholder('Ingresa tu contraseña',{exact:true}).inputValue(),'');
  const [[after]]=await db.execute('SELECT COUNT(*) n FROM users WHERE correo=?',['registration-ui@example.test']);assert.equal(Number(after.n),1);
  assert.deepEqual(errors,[]);
  console.log('OK UI registro real: error de correo conserva formulario, destinatario por email, seis casillas, sin SMS ni código visible, diseño 1440/430/320 px, rechazo del código incorrecto y alta confirmada en MySQL.');
} finally {await control('');await browser.close();await db.end();}
